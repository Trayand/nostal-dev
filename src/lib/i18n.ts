export const dictionaries = { id, en };

export function translate(lang: "id" | "en", key: I18nKey, vars?: Record<string, string | number>): string {
  let text = dictionaries[lang][key] ?? dictionaries.id[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}
